export function buildAffiliatePartnerContext() {
  return Object.values(AFFILIATES)
    .map((affiliate) => {
      return `- ${affiliate.brand}
  Website: ${affiliate.homepage}
  Categories: ${affiliate.category.join(", ")}
  Style / fit: ${affiliate.vibe.join(", ")}`;
    })
    .join("\n\n");
}

function hostnameFromUrl(url) {
  try {
    return new URL(url).hostname.replace(/^www\./i, "").toLowerCase();
  } catch {
    return "";
  }
}

export function getAffiliateDomains(affiliate) {
  const domains = new Set();
  const homepageHost = hostnameFromUrl(affiliate.homepage);
  if (homepageHost) {
    domains.add(homepageHost);
  }

  for (const term of affiliate.match || []) {
    if (term.includes(".")) {
      domains.add(term.replace(/^www\./i, "").toLowerCase());
    }
  }

  return [...domains];
}

export function detectAffiliateBrand({ title = "", retailer = "", url = "" }) {
  const text = `${title} ${retailer} ${url}`.toLowerCase();

  for (const [key, affiliate] of Object.entries(AFFILIATES)) {
    const terms = affiliate.match || [];
    if (terms.some((term) => text.includes(term.toLowerCase()))) {
      return key;
    }
  }

  return null;
}
